using Content.Shared._Nebula.DetailExaminable;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Utility;

namespace Content.Client.FlavorText;

// Neubla start
[GenerateTypedNameReferences]
public sealed partial class FlavorText : Control
{
    public Action<int>? OnFlavorTabChanged;

    public event Action<FlavorTextField, string>? OnTextChanged;

    private readonly Dictionary<FlavorTextField, TextEdit> _inputs = new();

    private bool _suppress;

    public FlavorText()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        var loc = IoCManager.Resolve<ILocalizationManager>();

        FlavorTabs.SetTabTitle(0, Loc.GetString("flavor-tab-flavor"));
        FlavorTabs.SetTabTitle(1, Loc.GetString("flavor-tab-character"));
        FlavorTabs.SetTabTitle(2, Loc.GetString("flavor-tab-ooc-flavor"));
        FlavorTabs.SetTabTitle(3, Loc.GetString("flavor-tab-gyr"));
        FlavorTabs.SetTabTitle(4, Loc.GetString("flavor-tab-nsfw"));
        FlavorTabs.SetTabTitle(5, Loc.GetString("flavor-tab-nsfw-ooc-flavor"));

        var fields = new (FlavorTextField Field, TextEdit Edit, string PlaceholderKey)[]
        {
                (FlavorTextField.Flavor, CFlavorTextInput, "flavor-text-placeholder-trauma"),
                (FlavorTextField.Character, CCharacterTextInput, "character-flavor-text-placeholder"),
                (FlavorTextField.FlavorOOC, CFlavorOOCTextInput, "ooc-flavor-text-placeholder"),
                (FlavorTextField.Tags, CTagsTextInput, "tags-flavor-text-placeholder"),
                (FlavorTextField.Links, CLinksTextInput, "links-flavor-text-placeholder"),
                (FlavorTextField.Green, CGreenTextInput, "green-flavor-text-placeholder"),
                (FlavorTextField.Yellow, CYellowTextInput, "yellow-flavor-text-placeholder"),
                (FlavorTextField.Red, CRedTextInput, "red-flavor-text-placeholder"),
                (FlavorTextField.NSFW, CNSFWTextInput, "nsfw-flavor-text-placeholder"),
                (FlavorTextField.NSFWOOC, CFlavorNSFWOOCTextInput, "ooc-flavor-text-placeholder"),
                (FlavorTextField.NSFWLinks, CNSFWLinksTextInput, "links-flavor-text-placeholder"),
                (FlavorTextField.NSFWTags, CNSFWTagsTextInput, "tags-flavor-text-placeholder"),
        };

        foreach (var (field, edit, placeholderKey) in fields)
        {
            edit.Placeholder = new Rope.Leaf(loc.GetString(placeholderKey));
            Bind(field, edit);
        }
    }

    public void FlavorTabChanged(int tab)
    {
        OnFlavorTabChanged?.Invoke(tab);
    }

    private void Bind(FlavorTextField field, TextEdit edit)
    {
        _inputs[field] = edit;
        edit.OnTextChanged += _ =>
        {
            if (_suppress) return;
            OnTextChanged?.Invoke(field, Rope.Collapse(edit.TextRope));
        };
    }

    public void SetText(FlavorTextField field, string text)
    {
        _suppress = true;
        _inputs[field].TextRope = new Rope.Leaf(text);
        _suppress = false;
    }

    public void SetData(DetailExaminableData data)
    {
        SetText(FlavorTextField.Flavor, data.FlavorText);
        SetText(FlavorTextField.Character, data.CharacterFlavorText);
        SetText(FlavorTextField.FlavorOOC, data.OOCFlavorText);
        SetText(FlavorTextField.Tags, data.TagsFlavorText);
        SetText(FlavorTextField.Links, data.LinksFlavorText);
        SetText(FlavorTextField.Green, data.GreenFlavorText);
        SetText(FlavorTextField.Yellow, data.YellowFlavorText);
        SetText(FlavorTextField.Red, data.RedFlavorText);
        SetText(FlavorTextField.NSFW, data.NSFWFlavorText);
        SetText(FlavorTextField.NSFWOOC, data.NSFWOOCFlavorText);
        SetText(FlavorTextField.NSFWLinks, data.NSFWLinksFlavorText);
        SetText(FlavorTextField.NSFWTags, data.NSFWTagsFlavorText);
    }
}

// Neubla end
