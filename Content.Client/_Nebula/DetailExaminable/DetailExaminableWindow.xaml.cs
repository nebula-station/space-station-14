    private readonly List<Direction> _rotationSequence = new()
    {
        Direction.East,
        Direction.North,
        Direction.West,
        Direction.South,
    };

    private static readonly (string Host, string PathPrefix)[] AllowedLinks =
    [
        ("docs.google.com", "/"),
        ("disk.yandex.by", "/"),
        ("disk.yandex.ru", "/"),
        ("docs.yandex.by", "/"),
        ("docs.yandex.ru", "/"),
        ("ru.imgbb.com", "/"),
        ("gyazo.com", "/"),
        ("i.gyazo.com", "/"),
        ("e621.net", "/"),
        ("static1.e621.net", "/"),
        ("e926.net", "/"),
        ("static1.e926.net", "/"),
        ("steamcommunity.com", "/id/"),
        ("steamcommunity.com", "/sharedfiles"),
        ("images.steamusercontent.com", "/"),
        ("media.discordapp.net", "/attachments"),
        ("cdn.discordapp.com", "/attachments"),
    ];

    private int _currentDirectionIndex = 3;
    private EntityUid? _currentEntity;
    private SpriteView? _spriteView;

    public DetailExaminableWindow()
    {
        RobustXamlLoader.Load(this);

        RotateLeftButton.OnPressed += _ => RotateDirection(-1);
        RotateRightButton.OnPressed += _ => RotateDirection(1);
        PreviewTabs.OnTabChanged += OnTabChanged;
    }

    #region Rotation

    private void RotateDirection(int step)
    {
        _currentDirectionIndex = (_currentDirectionIndex + step + _rotationSequence.Count) % _rotationSequence.Count;
        UpdateSpriteDirection();
    }

    #endregion
    #region Tabs

    private void UpdateNSFWPreviewVisibility(bool toggleNsfw)
    {
        if (PreviewTagsText.Visible == !toggleNsfw)
            return;

        PreviewLinksContainer.Visible = !toggleNsfw;
        PreviewNSFWLinksContainer.Visible = toggleNsfw;
        PreviewOOCText.Visible = !toggleNsfw;
        PreviewNSFWOOCText.Visible = toggleNsfw;
        PreviewTagsText.Visible = !toggleNsfw;
        PreviewNSFWTagsText.Visible = toggleNsfw;
    }
    private void OnTabChanged(int tab)
    {
        switch (tab)
        {
            case 3:
                UpdateNSFWPreviewVisibility(true);
                break;
            default:
                UpdateNSFWPreviewVisibility(false);
                break;
        }
    }

    #endregion
    #region Update states

    private void UpdateSpriteDirection()
    {
        if (_currentEntity == null || TargetPreview == null)
            return;

        TargetPreview.RemoveAllChildren();

        _spriteView = new SpriteView
        {
            OverrideDirection = _rotationSequence[_currentDirectionIndex],
            Scale = new Vector2(8f, 8f),
            MinSize = new Vector2(32, 128),
            Stretch = SpriteView.StretchMode.Fit,
        };

        _spriteView.SetEntity(_currentEntity.Value);
        TargetPreview.AddChild(_spriteView);
    }

    public void UpdateState(DetailExaminableEuiState state, IEntityManager entManager)
    {
        _currentEntity = entManager.GetEntity(state.Target);

        var data = state.Data;

        PreviewTabs.SetTabTitle(0, Loc.GetString("flavor-tab-flavor"));
        PreviewTabs.SetTabTitle(1, Loc.GetString("flavor-tab-character"));
        PreviewTabs.SetTabTitle(2, Loc.GetString("flavor-tab-gyr"));
        PreviewTabs.SetTabTitle(3, Loc.GetString("flavor-tab-nsfw"));

        var showNsfw = IsCharacterClothed(_currentEntity.Value, entManager);
        PreviewTabs.SetTabVisible(3, showNsfw);

        var sex = Loc.GetString($"humanoid-profile-editor-sex-{state.Sex.ToString().ToLower()}-text");
        var gender = Loc.GetString($"humanoid-profile-editor-pronouns-{state.Gender.ToString().ToLower()}-text");

        PreviewNameText.Text = state.Name;
        PreviewGenderText.Text = $"{state.SpeciesName} | {sex} | {gender}";

        UpdateSpriteDirection();

        SetText(PreviewAppearanceText, data.FlavorText, "detail-examinable-empty-flavor");
        SetText(PreviewTraitsText, data.CharacterFlavorText, "detail-examinable-empty-character");
        SetText(PreviewOOCText, data.OOCFlavorText, "detail-examinable-empty-ooc");
        SetText(PreviewOOCText, data.OOCFlavorText, "detail-examinable-empty-ooc");

        PreviewGYRContainer.RemoveAllChildren();
        AddGYRSection("humanoid-profile-editor-gyr-green", Color.Green, data.GreenFlavorText, "detail-examinable-empty-green");
        AddGYRSection("humanoid-profile-editor-gyr-yellow", Color.Yellow, data.YellowFlavorText, "detail-examinable-empty-yellow");
        AddGYRSection("humanoid-profile-editor-gyr-red", Color.Red, data.RedFlavorText, "detail-examinable-empty-red");

        PreviewTagsText.Text = data.TagsFlavorText;

        ProcessLinks(data.LinksFlavorText, PreviewLinksContainer);

        if (!showNsfw)
            return;

        SetText(PreviewNSFWText, data.NSFWFlavorText, "detail-examinable-empty-nsfw");
        SetText(PreviewNSFWOOCText, data.NSFWOOCFlavorText, "detail-examinable-empty-ooc");
        PreviewNSFWTagsText.Text = data.NSFWTagsFlavorText;
        ProcessLinks(data.NSFWLinksFlavorText, PreviewNSFWLinksContainer);
    }

    #endregion
    #region Text processing

    private void SetText(RichTextLabel label, string text, string emptyLoc)
    {
        label.SetMessage(GetContentWithEmptyMessage(text, emptyLoc));
    }

    private void AddGYRSection(string headerLoc, Color color, string text, string emptyLoc)
    {
        PreviewGYRContainer.AddChild(CreateSectionHeader(headerLoc, color));
        CreateGYRTextLabel(GetContentWithEmptyMessage(text, emptyLoc));
    }

    private Control CreateSectionHeader(string text, Color? color = null)
    {
        return new StripeBack
        {
            Children =
        {
            new Label
            {
                Text = Loc.GetString(text),
                StyleClasses = { "LabelBig" },
                Align = Label.AlignMode.Center,
                FontColorOverride = color,
            }
        }
        };
    }

    private static string GetContentWithEmptyMessage(string content, string emptyMessageKey)
    {
        if (string.IsNullOrEmpty(content))
            return Loc.GetString(emptyMessageKey);

        return content;
    }

    private void CreateGYRTextLabel(string text)
    {
        var label = new RichTextLabel
        {
            Text = text + "\n",
            VerticalExpand = true,
        };

        PreviewGYRContainer.AddChild(label);
    }

    #endregion
    #region Links processing


    private static bool IsValidUrl(string url)
    {
        const string prefix = "https://";

        if (!url.StartsWith(prefix, StringComparison.OrdinalIgnoreCase))
            return false;

        var rest = url.AsSpan(prefix.Length);

        var end = rest.IndexOfAny('/', '?', '#');
        var host = end < 0 ? rest : rest[..end];
        var path = end < 0 ? ReadOnlySpan<char>.Empty : rest[end..];

        if (host.IsEmpty || host.IndexOfAny('@', ':') >= 0)
            return false;

        foreach (var (allowedHost, allowedPath) in AllowedLinks)
        {
            if (host.Equals(allowedHost, StringComparison.OrdinalIgnoreCase) &&
                path.StartsWith(allowedPath, StringComparison.OrdinalIgnoreCase))
                return true;
        }

        return false;
    }
    private void ProcessLinks(string linksText, BoxContainer linksContainer)
    {
        linksContainer.RemoveAllChildren();

        if (string.IsNullOrEmpty(linksText))
        {
            AddGrayLabel(Loc.GetString("detail-examinable-empty-links"), linksContainer);
            return;
        }

        var links = linksText.Split(new[] { ',', ' ', '\n', '\r', '\t' }, StringSplitOptions.RemoveEmptyEntries);
        foreach (var link in links)
        {
            if (IsValidUrl(link))
                CreateLinkButton(link, linksContainer);
            else
                AddGrayLabel(link, linksContainer);
        }
    }

    private static void AddGrayLabel(string text, BoxContainer container)
    {
        container.AddChild(new Label
        {
            Text = text,
            HorizontalExpand = true,
            HorizontalAlignment = HAlignment.Center,
            FontColorOverride = Color.Gray,
        });
    }

    private void CreateLinkButton(string url, BoxContainer linksContainer)
    {
        var button = new Button
        {
            Text = url.Length > 40 ? url[..37] + "..." : url,
            ToolTip = Loc.GetString("humanoid-profile-editor-link-tooltip", ("url", url)),
            HorizontalExpand = true,
            HorizontalAlignment = HAlignment.Center,
            StyleClasses = { StyleClass.ButtonOpenBoth },
        };

        button.OnPressed += _ => IoCManager.Resolve<IUriOpener>().OpenUri(url);
        linksContainer.AddChild(button);
    }

    #endregion
    #region Functions

    private bool IsCharacterClothed(EntityUid entity, IEntityManager entManager) // Hide NSFW flavor if character is clothed
    {
        if (entity == EntityUid.Invalid)
            return false;

        var inventorySystem = entManager.System<InventorySystem>();

        return inventorySystem.TryGetSlotEntity(entity, "outerClothing", out _) ||
               inventorySystem.TryGetSlotEntity(entity, "jumpsuit", out _);
    }

    #endregion

    [Obsolete] // TODO Remove that in future
    protected override void Dispose(bool disposing)
    {
        if (disposing)
        {
            _spriteView?.Dispose();
            _spriteView = null;

            TargetPreview?.RemoveAllChildren();
        }

        base.Dispose(disposing);
    }
}
