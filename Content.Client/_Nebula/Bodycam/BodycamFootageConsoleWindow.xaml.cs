using System.Globalization;
using System.Linq;
using Content.Client.UserInterface.Controls;
using Content.Shared._Nebula.Bodycam;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Utility;

namespace Content.Client._Nebula.Bodycam;

[GenerateTypedNameReferences]
public sealed partial class BodycamFootageConsoleWindow : FancyWindow
{
    public event Action<int, TimeSpan, TimeSpan, bool>? OnRequest;
    public event Action? OnWatch;

    private BodycamFootageConsoleState? _state;
    private int? _selected;
    private bool _hasClip;

    public BodycamFootageConsoleWindow()
    {
        RobustXamlLoader.Load(this);

        CameraList.OnItemSelected += args =>
        {
            _selected = (int) CameraList[args.ItemIndex].Metadata!;
            RebuildSegments();
            UpdateControls();
        };
        CameraList.OnItemDeselected += _ =>
        {
            _selected = null;
            RebuildSegments();
            UpdateControls();
        };

        FromEdit.OnTextChanged += _ => UpdateControls();
        ToEdit.OnTextChanged += _ => UpdateControls();
        Last5Button.OnPressed += _ => SetLast(5);
        Last10Button.OnPressed += _ => SetLast(10);
        Last15Button.OnPressed += _ => SetLast(15);
        Last30Button.OnPressed += _ => SetLast(30);

        RequestButton.OnPressed += _ =>
        {
            if (_selected is { } id && TryGetRange(out var from, out var to))
                OnRequest?.Invoke(id, from, to, UnfilteredCheck.Visible && UnfilteredCheck.Pressed);
        };
        WatchButton.OnPressed += _ => OnWatch?.Invoke();
    }

    public void SetClip(string? clip)
    {
        _hasClip = clip != null;
        WatchButton.ToolTip = clip;
        UpdateControls();
    }

    public void UpdateState(BodycamFootageConsoleState state)
    {
        _state = state;

        RoundTimeLabel.Text = Loc.GetString("bodycam-footage-round-time", ("time", Format(state.RoundTime)));
        AvailabilityLabel.Text = Loc.GetString(state.Available ? "bodycam-footage-available" : "bodycam-footage-unavailable");
        UnfilteredCheck.Visible = state.CanUnfiltered;

        CameraList.Clear();
        foreach (var camera in state.Cameras)
        {
            var text = Loc.GetString(camera.Enabled ? "bodycam-footage-camera-on" : "bodycam-footage-camera-off", ("name", camera.Name));
            var item = CameraList.AddItem(text);
            item.Metadata = camera.Id;
            if (camera.Id == _selected)
                item.Selected = true;
        }

        if (_selected != null && state.Cameras.All(c => c.Id != _selected))
            _selected = null;

        var statusText = Loc.GetString($"bodycam-footage-status-{state.Status.ToString().ToLowerInvariant()}");
        if (state.StatusText != null)
            statusText += "\n" + FormattedMessage.EscapeText(state.StatusText);
        StatusLabel.SetMessage(FormattedMessage.FromMarkupPermissive(statusText));

        RebuildSegments();
        UpdateControls();
    }

    private void RebuildSegments()
    {
        SegmentList.RemoveAllChildren();
        if (_state == null || _selected == null)
            return;

        var camera = _state.Cameras.FirstOrDefault(c => c.Id == _selected);
        if (camera == null)
            return;

        if (camera.Segments.Count == 0)
        {
            SegmentList.AddChild(new Label { Text = Loc.GetString("bodycam-footage-no-segments") });
            return;
        }

        foreach (var segment in camera.Segments)
        {
            var text = Loc.GetString(segment.Open ? "bodycam-footage-segment-open" : "bodycam-footage-segment",
                ("from", Format(segment.Start)),
                ("to", Format(segment.End)),
                ("wearer", segment.Wearer));

            var button = new Button { Text = text, ClipText = true, HorizontalExpand = true };
            button.OnPressed += _ =>
            {
                var maxLength = TimeSpan.FromMinutes(_state.MaxMinutes);
                var start = segment.End - segment.Start > maxLength ? segment.End - maxLength : segment.Start;
                FromEdit.Text = Format(start);
                ToEdit.Text = Format(segment.End);
                UpdateControls();
            };
            SegmentList.AddChild(button);
        }
    }

    private void SetLast(int minutes)
    {
        if (_state == null)
            return;

        var end = _state.RoundTime;
        var camera = _selected == null ? null : _state.Cameras.FirstOrDefault(c => c.Id == _selected);
        if (camera is { Segments.Count: > 0 } && !camera.Segments[^1].Open)
            end = camera.Segments[^1].End;

        var start = end - TimeSpan.FromMinutes(minutes);
        if (start < TimeSpan.Zero)
            start = TimeSpan.Zero;

        FromEdit.Text = Format(start);
        ToEdit.Text = Format(end);
        UpdateControls();
    }

    private bool TryGetRange(out TimeSpan from, out TimeSpan to)
    {
        to = default;
        return TryParse(FromEdit.Text, out from) && TryParse(ToEdit.Text, out to) && to > from;
    }

    private void UpdateControls()
    {
        var busy = _state?.Status is BodycamFootageStatus.Queued or BodycamFootageStatus.Processing or BodycamFootageStatus.Sending;
        var valid = TryGetRange(out var from, out var to);
        var tooLong = valid && _state != null && (to - from).TotalMinutes > _state.MaxMinutes;

        LengthLabel.Text = !valid
            ? string.Empty
            : Loc.GetString(tooLong ? "bodycam-footage-length-too-long" : "bodycam-footage-length",
                ("length", Format(to - from)),
                ("max", _state?.MaxMinutes ?? 0));

        RequestButton.Disabled = _state is not { Available: true } || _selected == null || !valid || tooLong || busy;
        WatchButton.Disabled = !_hasClip || busy;
    }

    private static string Format(TimeSpan time)
    {
        return $"{(int) time.TotalHours:D2}:{time.Minutes:D2}:{time.Seconds:D2}";
    }

    private static bool TryParse(string text, out TimeSpan time)
    {
        time = default;
        var parts = text.Trim().Split(':');
        if (parts.Length is < 2 or > 3)
            return false;

        var values = new int[parts.Length];
        for (var i = 0; i < parts.Length; i++)
        {
            if (!int.TryParse(parts[i], NumberStyles.None, CultureInfo.InvariantCulture, out values[i]) || values[i] < 0)
                return false;
        }

        time = parts.Length == 3
            ? new TimeSpan(values[0], values[1], values[2])
            : new TimeSpan(0, values[0], values[1]);
        return true;
    }
}
