using Content.Client.UserInterface.Controls;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._Nebula.InfinityDorms.Exit;

[GenerateTypedNameReferences]
public sealed partial class InfinityDormExitWindow : FancyWindow
{
    public Action<bool>? ClosedToggled;
    public Action? ExitPressed;

    private bool _updating;

    public InfinityDormExitWindow()
    {
        RobustXamlLoader.Load(this);

        ClosedToggle.OnToggled += args =>
        {
            if (_updating)
                return;

            ClosedToggled?.Invoke(args.Pressed);
            _updating = true;
        };

        ExitButton.OnPressed += _ => ExitPressed?.Invoke();
    }

    public void UpdateState(bool closed, bool isOwner, int playersCount)
    {
        IsClosedLabel.Text = Loc.GetString("infinity-dorm-exit-ui-is-closed-answer", ("bool", closed));

        ClosedToggle.Pressed = closed;
        ClosedToggle.Disabled = !isOwner;
        OwnerHint.Visible = !isOwner;
        PlayersCount.Text = playersCount.ToString();

        _updating = false;
    }
}
