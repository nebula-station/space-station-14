using System.Linq;
using System.Numerics;
using Content.Client.UserInterface.Controls;
using Content.Shared._Nebula.InfinityDorms;
using Robust.Client.AutoGenerated;
using Robust.Client.GameObjects;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Prototypes;

namespace Content.Client._Nebula.InfinityDorms.Teleporter.Players;

[GenerateTypedNameReferences]
public sealed partial class InfinityDormPlayersWindow : FancyWindow
{
    [Dependency] private IPrototypeManager _proto = default!;
    [Dependency] private IEntitySystemManager _sysMan = default!;

    private readonly SpriteSystem _sprite;

    public InfinityDormPlayersWindow()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        _sprite = _sysMan.GetEntitySystem<SpriteSystem>();
    }

    public void Populate(List<List<InfinityDormVisitorData>> players)
    {
        PlayersContainer.RemoveAllChildren();

        if (players.Count == 0 || players.All(g => g.Count == 0))
        {
            PlayersContainer.AddChild(new Label
            {
                Text = Loc.GetString("infinity-dorm-players-ui-empty"),
                StyleClasses = { "LabelSubText" },
                HorizontalAlignment = HAlignment.Center,
                Margin = new Thickness(0, 8)
            });
            return;
        }

        for (var i = 0; i < players.Count; i++)
        {
            var group = players[i];
            if (group.Count == 0)
                continue;

            PlayersContainer.AddChild(new Label
            {
                Text = Loc.GetString("infinity-dorm-players-ui-group", ("index", i + 1), ("count", group.Count)),
                StyleClasses = { "LabelHeading" },
                Margin = new Thickness(0, 6, 0, 3)
            });

            foreach (var player in group)
            {
                PlayersContainer.AddChild(BuildRow(player));
            }
        }
    }

    private Control BuildRow(InfinityDormVisitorData player)
    {
        var row = new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Horizontal,
            Margin = new Thickness(8, 0, 0, 2)
        };

        if (_proto.TryIndex(player.JobIconProtoId, out var icon))
        {
            row.AddChild(new TextureRect
            {
                Texture = _sprite.Frame0(icon.Icon),
                TextureScale = new Vector2(2, 2),
                VerticalAlignment = VAlignment.Center
            });
        }

        row.AddChild(new Label
        {
            Text = player.UserName,
            Margin = new Thickness(6, 0)
        });

        return row;
    }
}
