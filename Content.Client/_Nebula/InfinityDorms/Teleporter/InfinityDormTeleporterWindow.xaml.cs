using System.Linq;
using Content.Client.UserInterface.Controls;
using Content.Shared._Nebula.InfinityDorms.Prototypes;
using Robust.Client.AutoGenerated;
using Robust.Client.Graphics;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Prototypes;

namespace Content.Client._Nebula.InfinityDorms.Teleporter;

[GenerateTypedNameReferences]
public sealed partial class InfinityDormTeleporterWindow : FancyWindow
{
    [Dependency] private IPrototypeManager _proto = default!;

    private readonly ButtonGroup _roomGroup = new();

    public Action? ConfirmPressed;
    public Action? PlayersListPressed;
    public Action? RoomsListPressed;

    public ProtoId<InfinityDormRoomCategoryPrototype>? CurrentRoomId;
    public int SelectedNumber = 0;
    public int MinValueForRoomId = 1;
    public int MaxValueForRoomId = 1;

    public InfinityDormTeleporterWindow()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        ReloadRooms();

        Confirm.OnPressed += _ => ConfirmPressed?.Invoke();
        PlayersListButton.OnPressed += _ => PlayersListPressed?.Invoke();
        RoomsListButton.OnPressed += _ => RoomsListPressed?.Invoke();

        NumberInput.OnTextChanged += OnInputChanged;
    }

    private void OnInputChanged(LineEdit.LineEditEventArgs args)
    {
        if (!int.TryParse(args.Text, out var value)
            || value < MinValueForRoomId
            || value >= MaxValueForRoomId
            || CurrentRoomId == null)
        {
            Confirm.Disabled = true;
            return;
        }

        SelectedNumber = value;
        Confirm.Disabled = false;
    }

    private Control BuildCategoryHeader(InfinityDormRoomCategoryPrototype category, int count)
    {
        var row = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Horizontal };

        row.AddChild(new PanelContainer
        {
            PanelOverride = new StyleBoxFlat { BackgroundColor = category.Color },
            MinWidth = 4
        });

        row.AddChild(new Label
        {
            Text = Loc.GetString("infinity-dorm-category-name-" + category.ID.ToLower()),
            StyleClasses = { "LabelHeading" },
            Margin = new Thickness(8, 3),
            HorizontalExpand = true
        });

        row.AddChild(new Label
        {
            Text = count.ToString(),
            StyleClasses = { "LabelSubText" },
            Margin = new Thickness(8, 3)
        });

        return new PanelContainer
        {
            PanelOverride = new StyleBoxFlat { BackgroundColor = category.Color.WithAlpha(0.15f) },
            Margin = new Thickness(0, 6, 0, 3),
            Children = { row }
        };
    }

    private void ReloadRooms()
    {
        RoomsContainer.RemoveAllChildren();

        var roomsByCategory = _proto.EnumeratePrototypes<InfinityDormRoomPrototype>()
            .GroupBy(r => r.Category.Id)
            .ToDictionary(g => g.Key, g => g.OrderBy(r => r.ID).ToList());

        var categories = _proto.EnumeratePrototypes<InfinityDormRoomCategoryPrototype>()
            .OrderBy(c => c.ID);

        foreach (var category in categories)
        {
            if (!roomsByCategory.TryGetValue(category.ID, out var rooms))
                continue;

            RoomsContainer.AddChild(BuildCategoryHeader(category, rooms.Count));

            foreach (var room in rooms)
            {
                var roomButton = new Button
                {
                    Text = Loc.GetString("infinity-dorm-room-name-" + room.ID.ToLower()),
                    ToolTip = Loc.GetString("infinity-dorm-room-desc-" + room.ID.ToLower()),
                    ToggleMode = true,
                    Group = _roomGroup,
                    HorizontalExpand = true,
                    Margin = new Thickness(12, 0, 0, 2),
                };

                var captured = room;
                roomButton.OnPressed += _ => SelectRoom(captured);

                RoomsContainer.AddChild(roomButton);
            }
        }
    }

    private void SelectRoom(InfinityDormRoomPrototype room)
    {
        CurrentRoomId = room.ID;
        CurrentRoom.Text = Loc.GetString("infinity-dorm-room-name-" + room.ID.ToLower());
        OnInputChanged(new LineEdit.LineEditEventArgs(NumberInput, NumberInput.Text));
    }
}
