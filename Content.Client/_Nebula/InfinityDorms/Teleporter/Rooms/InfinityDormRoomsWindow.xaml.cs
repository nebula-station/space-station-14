using Content.Client.UserInterface.Controls;
using Content.Shared._Nebula.InfinityDorms;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Timing;

namespace Content.Client._Nebula.InfinityDorms.Teleporter.Rooms;

[GenerateTypedNameReferences]
public sealed partial class InfinityDormRoomsWindow : FancyWindow
{
    [Dependency] private IGameTiming _timing = default!;
    private readonly List<(Label Label, TimeSpan Deadline)> _timers = [];

    public InfinityDormRoomsWindow()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);
    }

    public void Populate(IEnumerable<InfinityDormRoomData>? rooms)
    {
        RoomsContainer.RemoveAllChildren();
        _timers.Clear();

        var any = false;

        if (rooms != null)
        {
            foreach (var room in rooms)
            {
                any = true;
                RoomsContainer.AddChild(BuildCard(room));
            }
        }

        if (any)
            return;

        RoomsContainer.AddChild(new Label
        {
            Text = Loc.GetString("infinity-dorm-rooms-ui-empty"),
            StyleClasses = { "LabelSubText" },
            HorizontalAlignment = HAlignment.Center,
            Margin = new Thickness(0, 8)
        });
    }

    private Control BuildCard(InfinityDormRoomData room)
    {
        var box = new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Vertical,
            Margin = new Thickness(6, 4)
        };

        var header = new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Horizontal
        };

        header.AddChild(new Label
        {
            Text = string.IsNullOrWhiteSpace(room.RoomName)
                ? Loc.GetString("infinity-dorm-rooms-ui-unnamed")
                : room.RoomName,
            StyleClasses = { "LabelHeading" },
            HorizontalExpand = true,
            ClipText = true
        });

        header.AddChild(new Label
        {
            Text = Loc.GetString("infinity-dorm-rooms-ui-number", ("number", room.RoomNumber)),
            StyleClasses = { "LabelSubText" },
            VerticalAlignment = VAlignment.Center
        });

        box.AddChild(header);

        box.AddChild(new Label
        {
            Text = Loc.GetString("infinity-dorm-rooms-ui-visitors", ("count", room.Visitors)),
            Margin = new Thickness(8, 2, 0, 0)
        });

        if (room.DeletesAt != TimeSpan.Zero)
        {
            var timer = new Label
            {
                Margin = new Thickness(8, 0, 0, 0),
                StyleClasses = { "LabelSubText" },
                Text = FormatDeletion(room.DeletesAt)
            };

            _timers.Add((timer, room.DeletesAt));
            box.AddChild(timer);
        }

        return new PanelContainer
        {
            StyleClasses = { "PanelDark" },
            Margin = new Thickness(0, 0, 0, 4),
            Children = { box }
        };
    }

    private string FormatDeletion(TimeSpan deadline)
    {
        var left = deadline - _timing.CurTime;
        if (left < TimeSpan.Zero)
            left = TimeSpan.Zero;

        return Loc.GetString("infinity-dorm-rooms-ui-deletes",
            ("time", left.ToString(left.TotalHours >= 1 ? @"hh\:mm\:ss" : @"mm\:ss")));
    }

    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);

        foreach (var (label, deadline) in _timers)
        {
            label.Text = FormatDeletion(deadline);
        }
    }
}
