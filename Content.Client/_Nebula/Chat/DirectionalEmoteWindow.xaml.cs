using Content.Client._Nebula.Stylesheets;
using Content.Client._Nebula.UserInterface.Controls;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Timing;
using Robust.Shared.Utility;

namespace Content.Client._Nebula.Chat;

/// <summary>
/// Text box for a directional emote, seen only by the sender and the chosen target.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class DirectionalEmoteWindow : NebulaWindow
{
    [Dependency] private IUserInterfaceManager _ui = default!;
    [Dependency] private NebulaThemeManager _theme = default!;

    private Stylesheet? _baseStylesheet;

    public NetEntity Target { get; set; }

    public string Text { get; private set; } = string.Empty;

    public event Action? AcceptPressed;

    public event Action? MessageChanged;

    public DirectionalEmoteWindow()
    {
        XamlChildren = Contents.Children;
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        AcceptButton.OnPressed += _ => AcceptPressed?.Invoke();
        MessageInput.OnTextChanged += e =>
        {
            Text = Rope.Collapse(e.TextRope).Trim();
            MessageChanged?.Invoke();
        };
    }

    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);

        if (_ui.Stylesheet == _baseStylesheet)
            return;

        _baseStylesheet = _ui.Stylesheet;
        if (_baseStylesheet != null)
            Stylesheet = _theme.GetScopedStylesheet(_baseStylesheet);
    }
}
