    public ErpPanelWindow()
    {
        // NebulaWindow builds its frame in code, the XAML goes into its body
        XamlChildren = Contents.Children;
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        _sprite = _entManager.System<SpriteSystem>();
        _arousal = _entManager.System<ArousalSystem>();
        _interaction = _entManager.System<SharedInteractionSystem>();
        _mobState = _entManager.System<MobStateSystem>();

        ModifiersIcon.Texture = NebulaIcons.Get("settings");
        ClearSearchButton.Icon = NebulaIcons.Get("close");
        ApplyPalette(_theme.Palette);

        SearchInput.OnTextChanged += _ =>
        {
            ClearSearchButton.Disabled = string.IsNullOrWhiteSpace(SearchInput.Text);
            ReloadInteractionsIfNeeded(true);
        };
        ClearSearchButton.OnPressed += _ => SearchInput.Text = string.Empty;
        ClearSearchButton.Disabled = true;

        InitModifier(CustomArousalToggle, ArousalSlider, NCCVars.ErpArousalMultiplier);
        InitModifier(CustomMoaningToggle, MoaningSlider, NCCVars.ErpMoanMultiplier);

        ExpandAllButton.OnPressed += _ => SetAllCategoriesExpanded(true);
        CollapseAllButton.OnPressed += _ => SetAllCategoriesExpanded(false);
        ModifiersVisibilityButton.OnPressed += _ => SetModifiersVisible(!ModifiersContent.Visible);

        LungeToggle.Pressed = _cfg.GetCVar(NCCVars.ErpLungeEnabled);
        LungeToggle.OnToggled += args =>
        {
            _cfg.SetCVar(NCCVars.ErpLungeEnabled, args.Pressed);
            _cfg.SaveToFile();
        };

        UpdateMultiplierLabels();
        ArousalValueLabel.Text = FormatPercent(0);

        foreach (var id in _cfg.GetCVar(NCCVars.ErpFavoriteInteractions).Split(',', StringSplitOptions.RemoveEmptyEntries))
            _favorites.Add(id);

        _customEmotes = ErpCustomEmoteStorage.Load(_resources, _prototypeManager);
        CreateEmoteButton.OnPressed += _ => OpenEditor(null);
        UpdateCreateEmoteButton();
    }

