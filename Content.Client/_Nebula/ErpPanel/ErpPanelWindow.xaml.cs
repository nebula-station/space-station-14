    public void SetTarget(NetEntity user, NetEntity target)
    {
        _currentUser = _entManager.TryGetEntity(user, out var userUid) ? userUid : null;
        _currentTarget = _entManager.TryGetEntity(target, out var targetUid) ? targetUid : null;
        _currentInteractions.Clear();
        _openedCategories.Clear();
        _hasInitializedCategories = false;

        if (_currentUser == null || _currentTarget == null)
            return;

        var targetName = Identity.Name(_currentTarget.Value, _entManager, _currentUser.Value);
        HeaderLabel.Text = targetName;
        HeaderLabel.ToolTip = Loc.GetString("erp-panel-header", ("target", targetName));

        ReloadInteractionsIfNeeded(true);
    }

    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);

        if (!IsOpen)
            return;

        UpdateCooldowns();
        UpdateArousal();
        ReloadInteractionsIfNeeded();

        // clicking the panel raises it, keep the editor above
        if (_editor is { IsOpen: true } && _editor.Parent == Parent &&
            _editor.GetPositionInParent() < GetPositionInParent())
            _editor.MoveToFront();
    }

