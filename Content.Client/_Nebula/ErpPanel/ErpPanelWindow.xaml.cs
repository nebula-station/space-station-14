    {
        var grabber = NebulaStyleBox.Pill(NebulaPalette.Moonlight, color);
        grabber.SetContentMarginOverride(StyleBox.Margin.Horizontal, 6);

        slider.MaxValue = ErpPanelOwnerComponent.MaxMultiplier;
