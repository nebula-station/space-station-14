    private void UpdateCooldowns()
    {
        var now = _timing.CurTime;
        if (_lastCooldownUpdate + CooldownUpdateCooldown > now)
            return;

        _lastCooldownUpdate = now;

        foreach (var interactionId in _cooldownEnds.Keys.ToList())
        {
            var cooldownEnd = _cooldownEnds[interactionId];
            if (cooldownEnd <= now)
            {
                _cooldownEnds.Remove(interactionId);

                if (_interactionButtons.TryGetValue(interactionId, out var readyButton))
                {
                    readyButton.Disabled = false;
                    readyButton.ToolTip = readyButton.ReadyTooltip;
                }

                continue;
            }

            if (!_interactionButtons.TryGetValue(interactionId, out var button))
                continue;

            button.Disabled = true;
            var seconds = Math.Max(1, (int) Math.Ceiling((cooldownEnd - now).TotalSeconds));
            button.ToolTip = Loc.GetString("erp-panel-interaction-cooldown-tooltip", ("seconds", seconds));
        }
    }

    private void UpdateArousal()
    {
        if (_lastArousalUpdate + ArousalUpdateCooldown > _timing.CurTime)
            return;

        _lastArousalUpdate = _timing.CurTime;

        if (!_entManager.TryGetComponent<ArousalComponent>(_currentUser, out var userArousal) ||
            userArousal.MaxArousal <= 0)
        {
            SetArousalDisplay(0);
            return;
        }

        var percent = _arousal.GetArousal(userArousal) / userArousal.MaxArousal;
        SetArousalDisplay(Math.Clamp(percent, 0f, 1f));
    }

    private void SetArousalDisplay(float targetValue)
    {
        var difference = targetValue - ArousalProgressBar.Value;
        ArousalProgressBar.Value += 0.1f * difference;
        ArousalValueLabel.Text = FormatPercent(targetValue * 100);
    }

    private void ReloadInteractionsIfNeeded(bool force = false)
    {
        if (!_currentUser.HasValue || !_currentTarget.HasValue)
            return;

        force |= _reloadQueued;
        _reloadQueued = false;

        var now = _timing.CurTime;
        if (!force && now < _lastInteractionUpdate + ReloadCooldown)
            return;

        _lastInteractionUpdate = now;

        var interactions = GetAvailableInteractions(_currentUser.Value, _currentTarget.Value);
        var interactionIds = interactions
            .Select(interaction => interaction.ID)
            .ToList();

        interactionIds.Sort();
        interactionIds.AddRange(_availableCustomEmotes.Select(GetCustomEmoteKey));

        if (!force && _currentInteractions.SequenceEqual(interactionIds))
            return;

        _currentInteractions = interactionIds;
        ReloadInteractions(interactions);
    }

    private List<PanelInteractionPrototype> GetAvailableInteractions(EntityUid user, EntityUid target)
    {
        var searchText = SearchInput.Text.Trim();
        var interactions = new List<PanelInteractionPrototype>();

        // same rules as the server
        _rangeCache.Clear();
        _availableCustomEmotes.Clear();
        if (_mobState.IsIncapacitated(user) || _mobState.IsIncapacitated(target))
            return interactions;

        var softOnly = !_actionBlocker.CanInteract(user, target) ||
                       user != target && !_actionBlocker.CanInteract(target, null);

        foreach (var interaction in _prototypeManager.EnumeratePrototypes<PanelInteractionPrototype>())
        {
            if (softOnly && interaction.Kind != PanelInteractionKind.Soft)
                continue;

            if (!IsInteractionAvailable(user, target, interaction))
                continue;

            if (!InteractionMatchesSearch(interaction, searchText))
                continue;

            interactions.Add(interaction);
        }

        foreach (var emote in _customEmotes)
        {
            if (emote.Self != (user == target) || emote.Message.Length == 0)
                continue;

            if (softOnly && emote.Kind != PanelInteractionKind.Soft)
                continue;

            if (emote.IsErotic && !CanUseErp(user, target) || !IsInRange(user, target, ErpCustomEmote.Range))
                continue;

            if (searchText.Length > 0 && !emote.Name.Contains(searchText, StringComparison.CurrentCultureIgnoreCase))
                continue;

            _availableCustomEmotes.Add(emote);
        }

        return interactions;
    }

    private bool IsInteractionAvailable(EntityUid user, EntityUid target, PanelInteractionPrototype interaction)
    {
        if (user != target && interaction.Messages == null)
            return false;

        if (user == target && interaction.SelfMessages == null)
            return false;

        return CheckRequirements(user, target, interaction);
    }

    private void ReloadInteractions(List<PanelInteractionPrototype> interactions)
    {
        ButtonsContainer.RemoveAllChildren();
        _categoryControls.Clear();
        _interactionButtons.Clear();

        var interactionsByCategory = interactions
            .GroupBy(interaction => interaction.Category.Id)
            .ToDictionary(
                group => group.Key,
                group => group.OrderBy(GetInteractionName).ToList());

        var openFirstCategory = !_hasInitializedCategories && string.IsNullOrWhiteSpace(SearchInput.Text);

        var favorites = interactions.Where(interaction => _favorites.Contains(interaction.ID)).OrderBy(GetInteractionName).ToList();
        var customFavorites = _availableCustomEmotes.Where(emote => emote.Favorite).ToList();
        if (favorites.Count + customFavorites.Count > 0)
        {
            var grid = AddCategory(FavoritesCategoryId, Loc.GetString("erp-panel-favorites-category-name"),
                favorites.Count + customFavorites.Count, ref openFirstCategory);

            foreach (var interaction in favorites)
                grid.AddChild(PrepareInteractionButton(interaction, FavoritesCategoryId));

            foreach (var emote in customFavorites)
                grid.AddChild(PrepareCustomEmoteButton(emote, FavoritesCategoryId));
        }

        if (_availableCustomEmotes.Count > 0)
        {
            var grid = AddCategory(CustomCategoryId, Loc.GetString("erp-panel-custom-category-name"),
                _availableCustomEmotes.Count, ref openFirstCategory);

            foreach (var emote in _availableCustomEmotes)
                grid.AddChild(PrepareCustomEmoteButton(emote, CustomCategoryId));
        }

        foreach (var category in _prototypeManager.EnumeratePrototypes<PanelInteractionCategoryPrototype>())
        {
            if (!interactionsByCategory.TryGetValue(category.ID, out var categoryInteractions))
                continue;

            var categoryGrid = AddCategory(category.ID, GetCategoryName(category), categoryInteractions.Count, ref openFirstCategory);

            foreach (var interaction in categoryInteractions)
                categoryGrid.AddChild(PrepareInteractionButton(interaction, category.ID));
        }

        _hasInitializedCategories = true;
        UpdateCatalogSummary(interactions.Count + _availableCustomEmotes.Count);
        UpdateCooldownsImmediately();
    }

    private GridContainer AddCategory(string id, string name, int count, ref bool openFirst)
    {
        var categoryControl = PrepareInteractionCategory(id, name, count);
        var categoryGrid = new GridContainer
        {
            Columns = 2,
            HorizontalExpand = true,
            HSeparationOverride = 6,
            VSeparationOverride = 6,
            Margin = new Thickness(4, 6, 4, 2),
        };

        ButtonsContainer.AddChild(categoryControl);
        categoryControl.Body?.AddChild(categoryGrid);
        _categoryControls[id] = categoryControl;

        if (openFirst)
        {
            categoryControl.BodyVisible = true;
            _openedCategories.Add(id);
            openFirst = false;
        }

        return categoryGrid;
    }

    private Collapsible PrepareInteractionCategory(string categoryId, string categoryName, int count)
    {
        var title = Loc.GetString(
            "erp-panel-category-heading",
            ("category", categoryName),
            ("count", count));
        var heading = new CollapsibleHeading(title)
        {
            ChevronMargin = new Thickness(8, 0),
            HorizontalExpand = true,
            MinHeight = 34,
            StyleBoxOverride = CategoryStyle,
        };
        heading.Label.StyleClasses.Add(NebulaStyleClass.Title);
        heading.Label.HorizontalExpand = true;
        heading.Label.ClipText = true;
        heading.OnMouseEntered += _ => heading.StyleBoxOverride = CategoryHoverStyle;
        heading.OnMouseExited += _ => heading.StyleBoxOverride = CategoryStyle;

        var category = new Collapsible(heading, new CollapsibleBody())
        {
            HorizontalExpand = true,
        };

        heading.OnToggled += args =>
        {
            if (args.Pressed)
                _openedCategories.Add(categoryId);
            else
                _openedCategories.Remove(categoryId);
        };

        category.BodyVisible = !string.IsNullOrWhiteSpace(SearchInput.Text) ||
                               _openedCategories.Contains(categoryId);

        return category;
    }

