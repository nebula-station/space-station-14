    // multipliers are per-player cvars, the server applies them to their owner
    private void InitModifier(CheckBox toggle, Slider slider, CVarDef<float> cvar)
    {
        slider.MaxValue = ErpPanelOwnerComponent.MaxMultiplier;

        var value = _cfg.GetCVar(cvar);
        toggle.Pressed = !MathHelper.CloseTo(value, 100f);
        slider.Value = toggle.Pressed ? value : 100f;
        slider.Disabled = !toggle.Pressed;

        toggle.OnToggled += args =>
        {
            slider.Disabled = !args.Pressed;
            UpdateMultiplierLabels();
            SaveModifier(cvar, args.Pressed ? slider.Value : 100f);
        };
        slider.OnValueChanged += _ => UpdateMultiplierLabels();
        slider.OnReleased += _ => SaveModifier(cvar, slider.Value);
    }

    private void SaveModifier(CVarDef<float> cvar, float value)
    {
        _cfg.SetCVar(cvar, value);
        _cfg.SaveToFile();
    }

    private void UpdateCooldowns()
    {
        var now = _timing.CurTime;
        if (_lastCooldownUpdate + CooldownUpdateCooldown > now)
            return;

        _lastCooldownUpdate = now;

        foreach (var interactionId in _cooldownEnds.Keys.ToList())
        {
            var cooldownEnd = _cooldownEnds[interactionId];
            if (cooldownEnd <= now)
            {
                _cooldownEnds.Remove(interactionId);

                if (_interactionButtons.TryGetValue(interactionId, out var ready))
                {
                    ready.Button.Disabled = false;
                    ready.Button.ToolTip = ready.Tooltip;
                }

                continue;
            }

            if (!_interactionButtons.TryGetValue(interactionId, out var entry))
                continue;

            var button = entry.Button;
            button.Disabled = true;
            var seconds = Math.Max(1, (int) Math.Ceiling((cooldownEnd - now).TotalSeconds));
            button.ToolTip = Loc.GetString("erp-panel-interaction-cooldown-tooltip", ("seconds", seconds));
        }
    }

    private void UpdateArousal()
    {
        if (_lastArousalUpdate + ArousalUpdateCooldown > _timing.CurTime)
            return;

        _lastArousalUpdate = _timing.CurTime;

        if (!_entManager.TryGetComponent<ArousalComponent>(_currentUser, out var userArousal) ||
            userArousal.MaxArousal <= 0)
        {
            SetArousalDisplay(0);
            return;
        }

        var percent = _arousal.GetArousal(userArousal) / userArousal.MaxArousal;
        SetArousalDisplay(Math.Clamp(percent, 0f, 1f));
    }

    private void SetArousalDisplay(float targetValue)
    {
        var difference = targetValue - ArousalProgressBar.Value;
        ArousalProgressBar.Value += 0.1f * difference;
        ArousalValueLabel.Text = FormatPercent(targetValue * 100);
    }

    private void ReloadInteractionsIfNeeded(bool force = false)
    {
        if (!_currentUser.HasValue || !_currentTarget.HasValue)
            return;

        force |= _reloadQueued;
        _reloadQueued = false;

        var now = _timing.CurTime;
        if (!force && now < _lastInteractionUpdate + ReloadCooldown)
            return;

        _lastInteractionUpdate = now;

        var interactions = GetAvailableInteractions(_currentUser.Value, _currentTarget.Value);
        var interactionIds = interactions
            .Select(interaction => interaction.ID)
            .ToList();

        interactionIds.Sort();
        interactionIds.AddRange(_availableCustomEmotes.Select(GetCustomEmoteKey));
        if (_blockedMessage != null)
            interactionIds.Add(_blockedMessage);

        if (!force && _currentInteractions.SequenceEqual(interactionIds))
            return;

        _currentInteractions = interactionIds;
        ReloadInteractions(interactions);
    }

    private List<PanelInteractionPrototype> GetAvailableInteractions(EntityUid user, EntityUid target)
    {
        var searchText = SearchInput.Text.Trim();
        var interactions = new List<PanelInteractionPrototype>();

        // same rules as the server
        _rangeCache.Clear();
        _availableCustomEmotes.Clear();

        // cuffs don't matter, unconscious, stunned or sleeping sides can't take part
        _blockedMessage = _mobState.IsIncapacitated(user) || _mobState.IsIncapacitated(target)
            ? "erp-panel-empty-incapacitated"
            : IsBlocked(user) || IsBlocked(target)
                ? "erp-panel-empty-blocked"
                : null;

        if (_blockedMessage != null)
            return interactions;

        foreach (var interaction in _prototypeManager.EnumeratePrototypes<PanelInteractionPrototype>())
        {
            if (!IsInteractionAvailable(user, target, interaction))
                continue;

            if (!InteractionMatchesSearch(interaction, searchText))
                continue;

            interactions.Add(interaction);
        }

        foreach (var emote in _customEmotes)
        {
            if (emote.Self != (user == target) || emote.Message.Length == 0)
                continue;

            if (emote.IsErotic && !CanUseErp(user, target) || !IsInRange(user, target, ErpCustomEmote.Range))
                continue;

            if (searchText.Length > 0 && !emote.Name.Contains(searchText, StringComparison.CurrentCultureIgnoreCase))
                continue;

            _availableCustomEmotes.Add(emote);
        }

        return interactions;
    }

    private bool IsBlocked(EntityUid uid)
    {
        return _entManager.HasComponent<SleepingComponent>(uid) || _entManager.HasComponent<StunnedComponent>(uid);
    }

    private bool IsInteractionAvailable(EntityUid user, EntityUid target, PanelInteractionPrototype interaction)
    {
        if (user != target && interaction.Messages == null)
            return false;

        if (user == target && interaction.SelfMessages == null)
            return false;

        return CheckRequirements(user, target, interaction);
    }

    private void ReloadInteractions(List<PanelInteractionPrototype> interactions)
    {
        ButtonsContainer.RemoveAllChildren();
        _categoryControls.Clear();
        _interactionButtons.Clear();

        var interactionsByCategory = interactions
            .GroupBy(interaction => interaction.Category.Id)
            .ToDictionary(
                group => group.Key,
                group => group.OrderBy(GetInteractionName).ToList());

        var openFirstCategory = !_hasInitializedCategories && string.IsNullOrWhiteSpace(SearchInput.Text);

        var favorites = interactions.Where(interaction => _favorites.Contains(interaction.ID)).OrderBy(GetInteractionName).ToList();
        var customFavorites = _availableCustomEmotes.Where(emote => emote.Favorite).ToList();
        if (favorites.Count + customFavorites.Count > 0)
        {
            var grid = AddCategory(FavoritesCategoryId, Loc.GetString("erp-panel-favorites-category-name"),
                favorites.Count + customFavorites.Count, ref openFirstCategory);

            foreach (var interaction in favorites)
                grid.AddChild(PrepareInteractionButton(interaction, FavoritesCategoryId));

            foreach (var emote in customFavorites)
                grid.AddChild(PrepareCustomEmoteButton(emote, FavoritesCategoryId));
        }

        if (_availableCustomEmotes.Count > 0)
        {
            var grid = AddCategory(CustomCategoryId, Loc.GetString("erp-panel-custom-category-name"),
                _availableCustomEmotes.Count, ref openFirstCategory);

            foreach (var emote in _availableCustomEmotes)
                grid.AddChild(PrepareCustomEmoteButton(emote, CustomCategoryId));
        }

        foreach (var category in _prototypeManager.EnumeratePrototypes<PanelInteractionCategoryPrototype>())
        {
            if (!interactionsByCategory.TryGetValue(category.ID, out var categoryInteractions))
                continue;

            var categoryGrid = AddCategory(category.ID, GetCategoryName(category), categoryInteractions.Count, ref openFirstCategory);

            foreach (var interaction in categoryInteractions)
                categoryGrid.AddChild(PrepareInteractionButton(interaction, category.ID));
        }

        _hasInitializedCategories = true;
        UpdateCatalogSummary(interactions.Count + _availableCustomEmotes.Count);
        UpdateCooldownsImmediately();
    }

    private GridContainer AddCategory(string id, string name, int count, ref bool openFirst)
    {
        var categoryControl = PrepareInteractionCategory(id, name, count);
        var categoryGrid = new GridContainer
        {
            Columns = 2,
            HorizontalExpand = true,
            HSeparationOverride = 6,
            VSeparationOverride = 6,
            Margin = new Thickness(4, 6, 4, 2),
        };

        ButtonsContainer.AddChild(categoryControl);
        categoryControl.Body?.AddChild(categoryGrid);
        _categoryControls[id] = categoryControl;

        if (openFirst)
        {
            categoryControl.BodyVisible = true;
            _openedCategories.Add(id);
            openFirst = false;
        }

        return categoryGrid;
    }

    private Collapsible PrepareInteractionCategory(string categoryId, string categoryName, int count)
    {
        var title = Loc.GetString(
            "erp-panel-category-heading",
            ("category", categoryName),
            ("count", count));
        var heading = new CollapsibleHeading(title)
        {
            ChevronMargin = new Thickness(8, 0),
            HorizontalExpand = true,
            MinHeight = 34,
            StyleBoxOverride = _categoryStyle,
        };
        heading.Label.StyleClasses.Add(NebulaStyleClass.Title);
        heading.Label.HorizontalExpand = true;
        heading.Label.ClipText = true;
        heading.OnMouseEntered += _ => heading.StyleBoxOverride = _categoryHoverStyle;
        heading.OnMouseExited += _ => heading.StyleBoxOverride = _categoryStyle;

        var category = new Collapsible(heading, new CollapsibleBody())
        {
            HorizontalExpand = true,
        };

        heading.OnToggled += args =>
        {
            if (args.Pressed)
                _openedCategories.Add(categoryId);
            else
                _openedCategories.Remove(categoryId);
        };

        category.BodyVisible = !string.IsNullOrWhiteSpace(SearchInput.Text) ||
                               _openedCategories.Contains(categoryId);

        return category;
    }

    private void SetModifiersVisible(bool visible)
    {
        ModifiersContent.Visible = visible;
        ModifiersVisibilityButton.Text = Loc.GetString(
            visible ? "erp-panel-hide-modifiers" : "erp-panel-show-modifiers");
    }

    private Control PrepareInteractionButton(PanelInteractionPrototype interaction, string section)
    {
        return CreateInteractionButton(
            $"{section}/{interaction.ID}",
            GetInteractionName(interaction),
            interaction.Kind,
            _sprite.Frame0(interaction.Icon),
            () => OnSendEmote?.Invoke(interaction.ID, PrivateModeToggle.Pressed),
            _favorites.Contains(interaction.ID),
            () => ToggleFavorite(interaction.ID),
            null);
    }

    private Control PrepareCustomEmoteButton(ErpCustomEmote emote, string section)
    {
        var icon = _prototypeManager.TryIndex(emote.Category, out var category)
            ? _sprite.Frame0(category.Icon)
            : null;

        return CreateInteractionButton(
            $"{section}/{GetCustomEmoteKey(emote)}",
            emote.Name,
            emote.Kind,
            icon,
            () => OnSendCustomEmote?.Invoke(emote, PrivateModeToggle.Pressed),
            emote.Favorite,
            () => ToggleFavorite(emote),
            section == CustomCategoryId ? () => OpenEditor(emote) : null);
    }

    private Control CreateInteractionButton(
        string key,
        string interactionName,
        PanelInteractionKind kind,
        Texture? iconTexture,
        Action send,
        bool favorite,
        Action toggleFavorite,
        Action? edit)
    {
        var p = _theme.Palette;

        // no MinWidth, 2x250 overflowed the grid and overlapped the next button
        var button = new ShapedButton
        {
            HorizontalExpand = true,
            MinHeight = 56,
            ToolTip = interactionName,
        };
        button.AddStyleClass(NebulaStyleClass.ButtonChip);
        button.Content.HorizontalAlignment = HAlignment.Stretch;
        button.Content.HorizontalExpand = true;
        button.Content.Margin = new Thickness(7, 5);
        button.Content.SeparationOverride = 8;

        var accent = new ShapedPanel
        {
            MinWidth = 3,
            VerticalExpand = true,
            BackgroundColor = GetAccentColor(kind),
            Shape = ShapeStyle.Pill,
            MouseFilter = MouseFilterMode.Ignore,
        };
        var iconFrame = new ShapedPanel
        {
            MinWidth = 40,
            MinHeight = 40,
            BackgroundColor = p.Layer1,
            Shape = NebulaShapes.Control,
            MouseFilter = MouseFilterMode.Ignore,
        };
        iconFrame.AddChild(new TextureRect
        {
            Texture = iconTexture,
            MinWidth = 32,
            MinHeight = 32,
            HorizontalExpand = true,
            Stretch = TextureRect.StretchMode.KeepAspectCentered,
            VerticalAlignment = VAlignment.Center,
            MouseFilter = MouseFilterMode.Ignore,
        });
        var label = new Label
        {
            Text = interactionName,
            FontColorOverride = p.OnLayer2,
            ClipText = true,
            HorizontalExpand = true,
            VerticalAlignment = VAlignment.Center,
            MouseFilter = MouseFilterMode.Ignore,
        };

        button.OnPressed += _ =>
        {
            send();

            var cooldownEnd = _timing.CurTime + ErpPanelOwnerComponent.Cooldown;
            foreach (var interactionId in _interactionButtons.Keys)
                _cooldownEnds[interactionId] = cooldownEnd;
            UpdateCooldownsImmediately();
        };

        button.Content.AddChild(accent);
        button.Content.AddChild(iconFrame);
        button.Content.AddChild(label);
        if (edit != null)
            button.Content.AddChild(CreateIconButton(EditIcon, Loc.GetString("erp-panel-custom-edit-tooltip"), p.OnSurfaceVariant, edit));

        button.Content.AddChild(CreateIconButton(
            StarIcon,
            Loc.GetString(favorite ? "erp-panel-favorite-remove-tooltip" : "erp-panel-favorite-add-tooltip"),
            favorite ? p.Tertiary : p.Outline.WithAlpha(0.6f),
            toggleFavorite));
        _interactionButtons[key] = (button, interactionName);

        return button;
    }

    private static ShapedButton CreateIconButton(string icon, string tooltip, Color color, Action onPressed)
    {
        var button = new ShapedButton
        {
            Icon = NebulaIcons.Get(icon),
            IconSize = 16,
            MinWidth = 26,
            MinHeight = 26,
            VerticalAlignment = VAlignment.Center,
            ToolTip = tooltip,
            TextColorOverride = color,
        };
        button.AddStyleClass(NebulaStyleClass.ButtonGhost);
        button.OnPressed += _ => onPressed();
        return button;
    }

    private string GetCustomEmoteKey(ErpCustomEmote emote)
    {
        return $"custom:{_customEmotes.IndexOf(emote)}";
    }

    // the pressed button is rebuilt on reload, so it waits for the next frame
    private void ToggleFavorite(string interactionId)
    {
        if (!_favorites.Remove(interactionId))
            _favorites.Add(interactionId);

        _cfg.SetCVar(NCCVars.ErpFavoriteInteractions, string.Join(',', _favorites.Order()));
        _cfg.SaveToFile();
        _reloadQueued = true;
    }

    private void ToggleFavorite(ErpCustomEmote emote)
    {
        emote.Favorite = !emote.Favorite;
        SaveCustomEmotes();
    }

    private void OpenEditor(ErpCustomEmote? emote)
    {
        if (_editor == null)
        {
            _editor = new ErpCustomEmoteWindow();
            _editor.OnSave += SaveCustomEmote;
            _editor.OnDelete += DeleteCustomEmote;
            _editor.OnClose += () => _editor = null;
        }

        _editor.SetEmote(emote);
        _editor.OpenCentered();
    }

    private void SaveCustomEmote(ErpCustomEmote? original, ErpCustomEmote emote)
    {
        var index = original == null ? -1 : _customEmotes.IndexOf(original);
        if (index >= 0)
            _customEmotes[index] = emote;
        else if (_customEmotes.Count < ErpCustomEmote.MaxCount)
            _customEmotes.Add(emote);

        SaveCustomEmotes();
    }

    private void DeleteCustomEmote(ErpCustomEmote emote)
    {
        _customEmotes.Remove(emote);
        SaveCustomEmotes();
    }

    private void SaveCustomEmotes()
    {
        ErpCustomEmoteStorage.Save(_resources, _customEmotes);
        UpdateCreateEmoteButton();
        _reloadQueued = true;
    }

    private void UpdateCreateEmoteButton()
    {
        CreateEmoteButton.Disabled = _customEmotes.Count >= ErpCustomEmote.MaxCount;
        CreateEmoteButton.ToolTip = Loc.GetString("erp-panel-custom-create-tooltip",
            ("count", _customEmotes.Count),
            ("max", ErpCustomEmote.MaxCount));
    }

    private void UpdateCatalogSummary(int interactionCount)
    {
        ResultsLabel.Text = Loc.GetString("erp-panel-results", ("count", interactionCount));

        var hasInteractions = interactionCount > 0;
        InteractionScroll.Visible = hasInteractions;
        EmptyStateContainer.Visible = !hasInteractions;
        EmptyStateLabel.Text = Loc.GetString(
            _blockedMessage
            ?? (string.IsNullOrWhiteSpace(SearchInput.Text) ? "erp-panel-empty-available" : "erp-panel-empty-search"));

        ExpandAllButton.Disabled = _categoryControls.Count == 0;
        CollapseAllButton.Disabled = _categoryControls.Count == 0;
    }

    private void SetAllCategoriesExpanded(bool expanded)
    {
        foreach (var (categoryId, category) in _categoryControls)
        {
            category.BodyVisible = expanded;

            if (expanded)
                _openedCategories.Add(categoryId);
            else
                _openedCategories.Remove(categoryId);
        }
    }

    private void UpdateCooldownsImmediately()
    {
        _lastCooldownUpdate = _timing.CurTime - CooldownUpdateCooldown;
        UpdateCooldowns();
    }

    private bool InteractionMatchesSearch(PanelInteractionPrototype interaction, string searchText)
    {
        if (string.IsNullOrEmpty(searchText))
            return true;

        if (GetInteractionName(interaction).Contains(searchText, StringComparison.CurrentCultureIgnoreCase))
            return true;

        var category = _prototypeManager.Index<PanelInteractionCategoryPrototype>(interaction.Category.Id);
        return GetCategoryName(category).Contains(searchText, StringComparison.CurrentCultureIgnoreCase);
    }

    private string GetInteractionName(PanelInteractionPrototype interaction)
    {
        if (_interactionNames.TryGetValue(interaction.ID, out var name))
            return name;

        name = Loc.GetString($"erp-panel-interaction-{ToKebabCase(interaction.ID)}-name");
        _interactionNames[interaction.ID] = name;
        return name;
    }

    private string GetCategoryName(PanelInteractionCategoryPrototype category)
    {
        if (_categoryNames.TryGetValue(category.ID, out var name))
            return name;

        name = Loc.GetString($"erp-panel-category-{ToKebabCase(category.ID)}-name");
        _categoryNames[category.ID] = name;
        return name;
    }

    private static string FormatPercent(double value)
    {
        return $"{(int) Math.Round(value)}%";
    }

    internal static string ToKebabCase(string value)
    {
        var builder = new System.Text.StringBuilder(value.Length * 2);

        for (var i = 0; i < value.Length; i++)
        {
            var character = value[i];

            if (char.IsUpper(character))
            {
                if (i > 0)
                    builder.Append('-');

                builder.Append(char.ToLowerInvariant(character));
                continue;
            }

            builder.Append(character);
        }

        return builder.ToString();
    }

    private bool CheckRequirements(EntityUid user, EntityUid target, PanelInteractionPrototype interaction)
    {
        if (interaction.IsErotic && !CanUseErp(user, target))
            return false;

        if (!IsInRange(user, target, interaction.Range))
            return false;

        if (interaction.UserRequirements != null)
        {
            foreach (var requirement in interaction.UserRequirements)
            {
                if (!requirement.IsAvailable(user, _entManager))
                    return false;
            }
        }

        if (interaction.TargetRequirements != null)
        {
            foreach (var requirement in interaction.TargetRequirements)
            {
                if (!requirement.IsAvailable(target, _entManager))
                    return false;
            }
        }

        return true;
    }

    // same check as the server, one raycast per distinct range
    private bool IsInRange(EntityUid user, EntityUid target, float range)
    {
        if (_rangeCache.TryGetValue(range, out var inRange))
            return inRange;

        inRange = _interaction.InRangeAndAccessible(user, target, range);
        _rangeCache[range] = inRange;
        return inRange;
    }

    private bool CanUseErp(EntityUid user, EntityUid target)
    {
        if (!_entManager.TryGetComponent<ERPManagerComponent>(user, out var userErp) ||
            userErp.Status == ERPStatus.Never)
            return false;

        if (user == target)
            return true;

        return _entManager.TryGetComponent<ERPManagerComponent>(target, out var targetErp)
               && targetErp.Status != ERPStatus.Never;
    }
