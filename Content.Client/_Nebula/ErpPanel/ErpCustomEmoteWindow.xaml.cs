using System.Linq;
using Content.Client._Nebula.Stylesheets;
using Content.Client._Nebula.UserInterface.Controls;
using Content.Shared._Nebula.ErpPanel;
using Robust.Client.AutoGenerated;
using Robust.Client.GameObjects;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Audio.Systems;
using Robust.Shared.Player;
using Robust.Shared.Prototypes;
using Robust.Shared.Timing;

namespace Content.Client._Nebula.ErpPanel;

[GenerateTypedNameReferences]
public sealed partial class ErpCustomEmoteWindow : NebulaWindow
{
    [Dependency] private IEntityManager _entManager = default!;
    [Dependency] private IGameTiming _timing = default!;
    [Dependency] private IPrototypeManager _prototypeManager = default!;
    [Dependency] private IUserInterfaceManager _ui = default!;
    [Dependency] private NebulaThemeManager _theme = default!;

    private static readonly PanelInteractionKind[] Kinds = Enum.GetValues<PanelInteractionKind>();

    private readonly SpriteSystem _sprite;
    private readonly SharedAudioSystem _audio;
    private readonly List<PanelInteractionCategoryPrototype> _categories;
    private readonly List<PanelCustomSoundPrototype> _sounds;
    private Stylesheet? _baseStylesheet;
    private EntityUid? _preview;

    /// <summary>
    /// The emote being edited, null for a new one.
    /// </summary>
    public ErpCustomEmote? Editing { get; private set; }

    public event Action<ErpCustomEmote?, ErpCustomEmote>? OnSave;
    public event Action<ErpCustomEmote>? OnDelete;

    public ErpCustomEmoteWindow()
    {
        // NebulaWindow builds its frame in code, the XAML goes into its body
        XamlChildren = Contents.Children;
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        _sprite = _entManager.System<SpriteSystem>();
        _audio = _entManager.System<SharedAudioSystem>();

        NameInput.IsValid = text => text.Length <= ErpCustomEmote.MaxNameLength;
        MessageInput.IsValid = text => text.Length <= ErpCustomEmote.MaxMessageLength;

        var modeGroup = new ButtonGroup(false);
        TargetModeButton.Group = modeGroup;
        SelfModeButton.Group = modeGroup;
        TargetModeButton.OnPressed += _ => UpdateMode();
        SelfModeButton.OnPressed += _ => UpdateMode();

        _categories = _prototypeManager.EnumeratePrototypes<PanelInteractionCategoryPrototype>()
            .OrderBy(GetCategoryName)
            .ToList();
        for (var i = 0; i < _categories.Count; i++)
            CategorySelector.AddItem(GetCategoryName(_categories[i]), i);

        for (var i = 0; i < Kinds.Length; i++)
            KindSelector.AddItem(Loc.GetString($"erp-panel-kind-{ErpPanelWindow.ToKebabCase(Kinds[i].ToString())}"), i);

        _sounds = _prototypeManager.EnumeratePrototypes<PanelCustomSoundPrototype>()
            .OrderBy(GetSoundName)
            .ToList();
        SoundSelector.AddItem(Loc.GetString("erp-custom-emote-sound-none"), -1);
        for (var i = 0; i < _sounds.Count; i++)
            SoundSelector.AddItem(GetSoundName(_sounds[i]), i);

        CategorySelector.OnItemSelected += args =>
        {
            CategorySelector.SelectId(args.Id);
            UpdateIcon();
        };
        KindSelector.OnItemSelected += args => KindSelector.SelectId(args.Id);
        SoundSelector.OnItemSelected += args => SoundSelector.SelectId(args.Id);
        SoundSelector.OnPreview += PreviewSound;
        OnClose += () => _preview = _audio.Stop(_preview);

        CloseOnSecondClick(CategorySelector);
        CloseOnSecondClick(KindSelector);
        CloseOnSecondClick(SoundSelector);

        NameInput.OnTextChanged += _ => UpdateSaveButton();
        MessageInput.OnTextChanged += _ => UpdateSaveButton();

        SaveButton.OnPressed += _ => Save();
        CancelButton.OnPressed += _ => Close();
        DeleteButton.OnPressed += _ =>
        {
            if (Editing != null)
                OnDelete?.Invoke(Editing);

            Close();
        };
    }

    public void SetEmote(ErpCustomEmote? emote)
    {
        Editing = emote;
        Title = Loc.GetString(emote == null ? "erp-custom-emote-title-new" : "erp-custom-emote-title-edit");
        DeleteButton.Visible = emote != null;

        NameInput.Text = emote?.Name ?? string.Empty;
        MessageInput.Text = emote?.Message ?? string.Empty;
        TargetModeButton.Pressed = emote is not { Self: true };
        SelfModeButton.Pressed = emote is { Self: true };

        var category = emote == null ? -1 : _categories.FindIndex(c => c.ID == emote.Category.Id);
        CategorySelector.SelectId(Math.Max(category, 0));
        KindSelector.SelectId(Math.Max(Array.IndexOf(Kinds, emote?.Kind ?? PanelInteractionKind.Soft), 0));
        SoundSelector.SelectId(emote?.Sound is { } sound ? _sounds.FindIndex(s => s.ID == sound.Id) : -1);

        UpdateIcon();
        UpdateMode();
        UpdateSaveButton();
    }

    private void Save()
    {
        if (_categories.Count == 0)
            return;

        var emote = new ErpCustomEmote
        {
            Name = ErpCustomEmote.Sanitize(NameInput.Text, ErpCustomEmote.MaxNameLength),
            Category = _categories[CategorySelector.SelectedId].ID,
            Kind = Kinds[KindSelector.SelectedId],
            Sound = SoundSelector.SelectedId >= 0 ? _sounds[SoundSelector.SelectedId].ID : null,
            Message = ErpCustomEmote.Sanitize(MessageInput.Text, ErpCustomEmote.MaxMessageLength),
            Self = SelfModeButton.Pressed,
            Favorite = Editing?.Favorite ?? false,
        };

        if (emote.Name.Length == 0 || emote.Message.Length == 0)
            return;

        OnSave?.Invoke(Editing, emote);
        Close();
    }

    private void UpdateSaveButton()
    {
        SaveButton.Disabled = string.IsNullOrWhiteSpace(NameInput.Text) ||
                              string.IsNullOrWhiteSpace(MessageInput.Text);
    }

    private void UpdateMode()
    {
        var self = SelfModeButton.Pressed;
        MessageInput.PlaceHolder = Loc.GetString(self
            ? "erp-custom-emote-self-message-placeholder"
            : "erp-custom-emote-message-placeholder");
        HintLabel.Text = Loc.GetString(self ? "erp-custom-emote-hint-self" : "erp-custom-emote-hint");
    }

    private void UpdateIcon()
    {
        IconPreview.Texture = _categories.Count > 0
            ? _sprite.Frame0(_categories[CategorySelector.SelectedId].Icon)
            : null;
    }

    private string GetCategoryName(PanelInteractionCategoryPrototype category)
    {
        return Loc.GetString($"erp-panel-category-{ErpPanelWindow.ToKebabCase(category.ID)}-name");
    }

    /// <summary>
    /// The engine closes an open dropdown on mouse down and the release opens it again,
    /// so a click on its own button only blinks it. Here that click keeps it closed.
    /// </summary>
    private void CloseOnSecondClick(OptionButton button)
    {
        if (button.OptionsScroll.Parent is not Popup popup)
            return;

        uint closedFrame = 0;
        var keepClosed = false;

        popup.OnPopupHide += () => closedFrame = _timing.CurFrame;
        button.OnButtonDown += _ => keepClosed = closedFrame == _timing.CurFrame;
        button.OnPressed += _ =>
        {
            // runs after the button's own handler that reopened it
            if (keepClosed)
                popup.Close();

            keepClosed = false;
        };
    }

    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);

        // switching the HUD theme replaces the root stylesheet without an event
        if (_ui.Stylesheet == _baseStylesheet)
            return;

        _baseStylesheet = _ui.Stylesheet;
        if (_baseStylesheet != null)
            Stylesheet = _theme.GetScopedStylesheet(_baseStylesheet);
    }

    /// <summary>
    /// Plays the sound to this client only, a new preview cuts the previous one.
    /// </summary>
    private void PreviewSound(int id)
    {
        if (id < 0 || id >= _sounds.Count)
            return;

        _audio.Stop(_preview);
        _preview = _audio.PlayGlobal(_sounds[id].Sound, Filter.Local(), false)?.Entity;
    }

    private string GetSoundName(PanelCustomSoundPrototype sound)
    {
        return Loc.GetString($"erp-panel-custom-sound-{ErpPanelWindow.ToKebabCase(sound.ID)}-name");
    }
}
