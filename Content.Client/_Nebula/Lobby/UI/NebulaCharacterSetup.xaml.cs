namespace Content.Client._Nebula.Lobby.UI;

/// <summary>
/// Character setup screen: character slots on the left and the profile editor on the right.
/// Replaces <see cref="CharacterSetupGui"/> with the same API, the editor is restyled with
/// <see cref="NebulaScopedStylesheet"/>.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class NebulaCharacterSetup : Control
{
    [Dependency] private IClientPreferencesManager _preferences = default!;
    [Dependency] private IPrototypeManager _prototypes = default!;
    [Dependency] private IConfigurationManager _cfg = default!;
    [Dependency] private IClientConsoleHost _console = default!;
    [Dependency] private IUserInterfaceManager _ui = default!;
    [Dependency] private NebulaThemeManager _theme = default!;

    public event Action<int>? SelectCharacter;
    public event Action<int>? DeleteCharacter;

    public BaseButton CloseButton => CloseButtonControl;

    private Stylesheet? _baseStylesheet;

    public NebulaCharacterSetup(HumanoidProfileEditor profileEditor)
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        TitleIcon.Texture = NebulaIcons.Get("person_edit");
        NewCharacter.Icon = NebulaIcons.Get("person_add");
        StatsButton.Icon = NebulaIcons.Get("query_stats");
        RulesButton.Icon = NebulaIcons.Get("gavel");
        AdminRemarksButton.Icon = NebulaIcons.Get("sticky_note_2");
        CloseButtonControl.Icon = NebulaIcons.Get("close");

        NewCharacter.OnPressed += args =>
        {
            _preferences.CreateCharacter(HumanoidCharacterProfile.Random().WithJobFromCvar(_cfg));
            ReloadCharacterPickers();
            args.Event.Handle();
        };

        StatsButton.OnPressed += _ => new PlaytimeStatsWindow().OpenCentered();
        RulesButton.OnPressed += _ => new RulesAndInfoWindow().Open();
        AdminRemarksButton.OnPressed += _ => _console.ExecuteCommand("adminremarks");

        RestyleHighlights(profileEditor);
        CharEditor.AddChild(profileEditor);
    }

    protected override void EnteredTree()
    {
        base.EnteredTree();

        ApplyStylesheet(_theme.Palette);
        _theme.PaletteChanged += ApplyStylesheet;
        _cfg.OnValueChanged(CCVars.SeeOwnNotes, SetRemarksVisible, true);
        _cfg.OnValueChanged(CCVars.GameMaxCharacterSlots, OnMaxSlotsChanged);

        for (var parent = Parent; parent != null; parent = parent.Parent)
        {
            if (parent is not NebulaLobby lobby)
                continue;

            SlotsPanel.Backdrop = lobby.Background;
            EditorPanel.Backdrop = lobby.Background;
            break;
        }
    }

    protected override void ExitedTree()
    {
        base.ExitedTree();

        _theme.PaletteChanged -= ApplyStylesheet;
        _cfg.UnsubValueChanged(CCVars.SeeOwnNotes, SetRemarksVisible);
        _cfg.UnsubValueChanged(CCVars.GameMaxCharacterSlots, OnMaxSlotsChanged);
    }

    public void ReloadCharacterPickers()
    {
        Characters.RemoveAllChildren();

        if (!_preferences.ServerDataLoaded || _preferences.Preferences is not { } preferences)
        {
            SlotCount.Text = string.Empty;
            return;
        }

        var maxSlots = _cfg.GetCVar(CCVars.GameMaxCharacterSlots);
        var group = new ButtonGroup();
        var deleteIcon = NebulaIcons.Get("delete");
        var used = 0;

        foreach (var (slot, character) in preferences.Characters)
        {
            used++;

            if (character is not HumanoidCharacterProfile profile)
                continue;

            var button = new NebulaCharacterSlot(_prototypes,
                group,
                profile,
                slot == preferences.SelectedCharacterIndex,
                deleteIcon);

            if (slot >= maxSlots)
            {
                button.Disabled = true;
                button.Content.Modulate = Color.White.WithAlpha(0.5f);
                button.ToolTip = Loc.GetString("character-setup-gui-create-new-character-button-tooltip",
                    ("maxCharacters", maxSlots));
            }

            button.OnPressed += _ => SelectCharacter?.Invoke(slot);
            button.OnDeletePressed += () =>
            {
                Characters.RemoveChild(button);
                DeleteCharacter?.Invoke(slot);
            };

            Characters.AddChild(button);
        }

        SlotCount.Text = Loc.GetString("nebula-character-setup-slots", ("count", used), ("max", maxSlots));
        NewCharacter.Disabled = used >= maxSlots;
        NewCharacter.ToolTip = Loc.GetString("character-setup-gui-create-new-character-button-tooltip",
            ("maxCharacters", maxSlots));
    }

    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);

        // Switching the HUD theme replaces the root stylesheet without an event.
        if (_ui.Stylesheet != _baseStylesheet)
            ApplyStylesheet(_theme.Palette);
    }

    private void ApplyStylesheet(NebulaPalette palette)
    {
        _baseStylesheet = _ui.Stylesheet;

        if (_baseStylesheet == null)
            return;

        var stylesheet = _theme.GetScopedStylesheet(_baseStylesheet);

        if (Stylesheet != stylesheet)
            Stylesheet = stylesheet;
    }

    private void SetRemarksVisible(bool visible)
    {
        AdminRemarksButton.Visible = visible;
    }

    private void OnMaxSlotsChanged(int _)
    {
        ReloadCharacterPickers();
    }

    /// <summary>
    /// The editor's highlighted boxes paint a fixed color through PanelOverride, swap it for the Nebula section.
    /// </summary>
    private static void RestyleHighlights(Control control)
    {
        foreach (var child in control.Children)
        {
            if (child is HighlightedContainer highlight)
            {
                highlight.PanelOverride = null;
                highlight.AddStyleClass(NebulaStyleClass.VanillaSection);
            }

            RestyleHighlights(child);
        }
    }
}
