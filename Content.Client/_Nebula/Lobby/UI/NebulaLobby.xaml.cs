using Robust.Shared.Input;
using Robust.Shared.Timing;

namespace Content.Client._Nebula.Lobby.UI;

/// <summary>
/// Lobby screen: a top bar over the lobby art with a character and round panel on the left and chat on the right.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class NebulaLobby : Control
{
    [Dependency] private IBaseClient _baseClient = default!;
    [Dependency] private IConfigurationManager _cfg = default!;
    [Dependency] private IEntitySystemManager _entitySystems = default!;

    public const float BarHeight = 40f;

    private const float VoteGap = 8f;

    private BaseWindow? _observeWindow;
    private ClientGameTicker? _gameTicker;
    private bool? _gameStarted;

    private ShapedPanel _leftSidePanel = default!;
    private ShapedPanel _rightSidePanel = default!;

    public NebulaLobby()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        BarSpacer.MinHeight = BarHeight;
        LayoutContainer.SetAnchorPreset(Votes, LayoutContainer.LayoutPreset.CenterTop);
        LayoutContainer.SetGrowHorizontal(Votes, LayoutContainer.GrowDirection.Both);
        LayoutContainer.SetMarginTop(Votes, BarHeight + VoteGap);
        LayoutContainer.SetMarginBottom(Votes, BarHeight + VoteGap);
        Bar.MinHeight = BarHeight;
        ScreenFrame.HoleInset = new Thickness(0f, BarHeight, 0f, 0f);

        Background.BlurEnabled = true;
        LeftPanel.Backdrop = Background;
        RightPanel.Backdrop = Background;

        ObserveButton.Icon = NebulaIcons.Get("visibility");
        AHelpButton.Icon = NebulaIcons.Get("support_agent");
        OptionsButton.Icon = NebulaIcons.Get("settings");
        LeaveButton.Icon = NebulaIcons.Get("logout");

        ObserveButton.OnPressed += _ => ToggleObserveWindow();

        InitBarInfo();
        InitManifest();
        NebulaChatStyle.Apply(Chat);

        LeftHalf.OnKeyBindDown += args => OnHalfClicked(args, _leftSidePanel, LeftCorner);
        RightHalf.OnKeyBindDown += args => OnHalfClicked(args, _rightSidePanel, RightCorner);

        SetChatLeft(_cfg.GetCVar(NCCVars.LobbyChatLeft));
    }

    private void SetChatLeft(bool chatLeft)
    {
        _leftSidePanel = chatLeft ? RightPanel : LeftPanel;
        _rightSidePanel = chatLeft ? LeftPanel : RightPanel;

        _leftSidePanel.SetPositionFirst();
        _rightSidePanel.SetPositionLast();

        UpdateCorner(_leftSidePanel, LeftCorner);
        UpdateCorner(_rightSidePanel, RightCorner);
    }

    public void SetCharacterSetupVisible(bool visible)
    {
        DefaultState.Visible = !visible;
        CharacterSetupState.Visible = visible;
    }

    protected override void EnteredTree()
    {
        base.EnteredTree();

        ServerCaption.Text = _baseClient.GameInfo?.ServerName ?? string.Empty;
        _gameStarted = null;
        _shownPreferences = null;
        _entitySystems.TryGetEntitySystem(out _jobs);

        if (_entitySystems.TryGetEntitySystem(out _gameTicker))
            _gameTicker.InfoBlobUpdated += UpdateRoundInfo;

        _theme.PaletteChanged += OnPaletteChanged;
        _cfg.OnValueChanged(NCCVars.LobbyChatLeft, SetChatLeft, true);
        _cfg.OnValueChanged(CCVars.CrewManifestWithoutEntity, OnManifestCVarChanged);
        _cfg.OnValueChanged(NCCVars.LobbyReadyManifest, OnManifestCVarChanged);

        UpdateRoundInfo();
    }

    protected override void ExitedTree()
    {
        base.ExitedTree();

        _observeWindow?.Close();

        if (_gameTicker != null)
            _gameTicker.InfoBlobUpdated -= UpdateRoundInfo;

        _theme.PaletteChanged -= OnPaletteChanged;
        _cfg.UnsubValueChanged(NCCVars.LobbyChatLeft, SetChatLeft);
        _cfg.UnsubValueChanged(CCVars.CrewManifestWithoutEntity, OnManifestCVarChanged);
        _cfg.UnsubValueChanged(NCCVars.LobbyReadyManifest, OnManifestCVarChanged);

        _gameTicker = null;
        _jobs = null;
    }

    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);

        var hasStationTime = !string.IsNullOrEmpty(StationTime.Text);
        var hasStartTime = !string.IsNullOrEmpty(StartTime.Text);

        StationTime.Visible = hasStationTime;
        StartTime.Visible = hasStartTime;
        TimeSeparator.Visible = hasStationTime && hasStartTime;

        UpdatePhase();
        UpdateRoleIfChanged();
    }

    private void OnPaletteChanged(NebulaPalette palette)
    {
        // Department colors depend on the palette, forces the role icon to refresh.
        _shownPreferences = null;
    }

    private void UpdatePhase()
    {
        var started = _gameTicker?.IsGameStarted ?? false;

        if (_gameStarted == started)
            return;

        _gameStarted = started;
        PhaseTitle.Text = Loc.GetString(started ? "nebula-lobby-phase-in-round" : "nebula-lobby-phase-preround");
        UpdatePlayers();
        UpdateManifestButton();
    }

    private void UpdateRoundInfo()
    {
        var map = _gameTicker?.LobbyMapName ?? string.Empty;
        var mode = _gameTicker?.LobbyModeTitle ?? string.Empty;

        MapLabel.Text = map;
        ModeLabel.Text = mode;
        MapLabel.Visible = map.Length > 0;
        ModeLabel.Visible = mode.Length > 0;
        RoundInfoSeparator.Visible = MapLabel.Visible && ModeLabel.Visible;
        RoundInfoGroup.Visible = MapLabel.Visible || ModeLabel.Visible;

        UpdatePlayers();
    }

    private void OnHalfClicked(GUIBoundKeyEventArgs args, ShapedPanel panel, ShapedPanel corner)
    {
        if (args.Function != EngineKeyFunctions.UIClick)
            return;

        panel.Visible = !panel.Visible;
        UpdateCorner(panel, corner);
        args.Handle();
    }

    private static void UpdateCorner(ShapedPanel panel, ShapedPanel corner)
    {
        corner.RemoveStyleClass(panel.Visible ? NebulaStyleClass.BarCorner : NebulaStyleClass.BarCornerActive);
        corner.AddStyleClass(panel.Visible ? NebulaStyleClass.BarCornerActive : NebulaStyleClass.BarCorner);
    }

    private void ToggleObserveWindow()
    {
        if (_observeWindow is { IsOpen: true })
        {
            _observeWindow.Close();
            return;
        }

        _observeWindow = new NebulaObserveWindow();
        _observeWindow.OpenCentered();
    }
}
