using Content.Client._Nebula.UserInterface;
using Content.Shared.Humanoid.Prototypes;
using Content.Shared.Preferences;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Prototypes;

namespace Content.Client._Nebula.Lobby.UI;

/// <summary>
/// Selected character in the lobby side panel: sprite, name and buttons to edit the character or its loadouts.
/// Replaces <see cref="Content.Client.Lobby.UI.LobbyCharacterPreviewPanel"/>.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class NebulaCharacterPanel : Control
{
    [Dependency] private IPrototypeManager _prototypes = default!;

    public BaseButton CharacterSetupButton => CharacterSetup;

    public BaseButton WardrobeButton => Wardrobe;

    public NebulaCharacterPanel()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        CharacterSetup.Icon = NebulaIcons.Get("person_edit");
        Wardrobe.Icon = NebulaIcons.Get("checkroom");
        PatronPerks.Icon = NebulaIcons.Get("workspace_premium");
    }

    public void SetLoaded(bool value)
    {
        Loaded.Visible = value;
        Unloaded.Visible = !value;
    }

    public void SetProfile(HumanoidCharacterProfile? profile)
    {
        if (profile == null)
        {
            NameLabel.Text = string.Empty;
            DetailsLabel.Text = string.Empty;
            return;
        }

        var species = profile.CustomSpecies;

        if (string.IsNullOrWhiteSpace(species))
        {
            species = _prototypes.TryIndex<SpeciesPrototype>(profile.Species, out var speciesProto)
                ? Loc.GetString(speciesProto.Name)
                : profile.Species.Id;
        }

        NameLabel.Text = profile.Name;
        DetailsLabel.Text = Loc.GetString("nebula-lobby-character-details", ("species", species), ("age", profile.Age));
    }
}
