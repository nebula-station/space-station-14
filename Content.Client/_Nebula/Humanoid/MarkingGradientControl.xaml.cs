using Content.Shared._Nebula.Humanoid.Markings;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._Nebula.Humanoid;

/// <summary>
/// Edits the gradient of a single marking. Turning it off keeps the settings until the control is gone.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class MarkingGradientControl : BoxContainer
{
    private MarkingGradient _gradient = new();
    private Color _roots = Color.White;
    private MarkingGradientSuggestion? _lastSuggestion;
    private int _suggestionVariant;

    /// <summary>
    /// Raised when the user changes something, with null if the gradient is off.
    /// </summary>
    public event Action<MarkingGradient?>? GradientChanged;

    public event Action? SwapPressed;

    public MarkingGradientControl()
    {
        RobustXamlLoader.Load(this);

        foreach (var style in Enum.GetValues<MarkingGradientStyle>())
        {
            StyleOption.AddItem(Loc.GetString(StyleKey("style", style)), (int) style);
        }

        EnabledCheck.OnToggled += _ => Raise();
        SwapButton.OnPressed += _ => SwapPressed?.Invoke();
        LighterButton.OnPressed += _ => Suggest(MarkingGradientSuggestion.Lighter);
        AnalogousButton.OnPressed += _ => Suggest(MarkingGradientSuggestion.Analogous);
        ContrastButton.OnPressed += _ => Suggest(MarkingGradientSuggestion.Contrast);
        ResetButton.OnPressed += _ =>
        {
            _gradient.Offset = new MarkingGradient().Offset;
            Raise();
        };
        StyleOption.OnItemSelected += args =>
        {
            StyleOption.SelectId(args.Id);
            _gradient.Style = (MarkingGradientStyle) args.Id;
            Raise();
        };
        ColorSelector.OnColorChanged += color =>
        {
            _gradient.Color = color;
            Raise();
        };
        AmountSlider.OnValueChanged += range =>
        {
            _gradient.Offset = range.Value;
            Raise();
        };

        UpdateControls();
    }

    /// <summary>
    /// Shows the given state without raising <see cref="GradientChanged"/>.
    /// </summary>
    /// <param name="gradient">The marking's gradient, null if it has none.</param>
    /// <param name="roots">The marking's first color, which color suggestions start from.</param>
    public void SetGradient(MarkingGradient? gradient, Color roots)
    {
        _roots = roots;
        EnabledCheck.Pressed = gradient is not null;

        if (gradient is { } value)
            _gradient = value;

        UpdateControls();
    }

    /// <summary>
    /// Pressing the same button again moves on to its next variant, another button starts from its first one.
    /// </summary>
    private void Suggest(MarkingGradientSuggestion kind)
    {
        _suggestionVariant = kind == _lastSuggestion ? _suggestionVariant + 1 : 0;
        _lastSuggestion = kind;
        _gradient.Color = MarkingGradientPalette.Suggest(_roots, kind, _suggestionVariant);
        Raise();
    }

    private void Raise()
    {
        UpdateControls();
        GradientChanged?.Invoke(EnabledCheck.Pressed ? _gradient : null);
    }

    /// <summary>
    /// Syncs the controls with the state. The color is only written when it differs,
    /// because writing it back would make the HSV sliders lose their hue on black and white.
    /// </summary>
    private void UpdateControls()
    {
        Settings.Visible = EnabledCheck.Pressed;
        StyleOption.SelectId((int) _gradient.Style);

        if (ColorSelector.Color != _gradient.Color)
            ColorSelector.Color = _gradient.Color;

        AmountSlider.SetValueWithoutEvent(_gradient.Offset);

        ColorLabel.Text = Loc.GetString(StyleKey("color", _gradient.Style));
        AmountLabel.Text = Loc.GetString(StyleKey("amount", _gradient.Style), ("value", (int) MathF.Round(_gradient.Offset * 100f)));
    }

    private static string StyleKey(string kind, MarkingGradientStyle style)
    {
        return $"marking-gradient-{kind}-{style.ToString().ToLowerInvariant()}";
    }
}
