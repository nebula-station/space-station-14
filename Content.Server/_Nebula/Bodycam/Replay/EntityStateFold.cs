using System.Collections.Concurrent;
using System.Linq;
using System.Reflection;
using System.Runtime.CompilerServices;
using Robust.Shared.GameStates;
using Robust.Shared.Timing;

namespace Content.Server._Nebula.Bodycam.Replay;

public sealed class EntityStateFold
{
    public sealed class Entry
    {
        public readonly Dictionary<ushort, ComponentChange> Components = new();
        public readonly Dictionary<ushort, ComponentChange> PendingDeltas = new();
        public HashSet<ushort>? NetComponents;
        public GameTick LastModified;
    }

    private static readonly ConcurrentDictionary<Type, (FieldInfo[] All, (FieldInfo Field, int Index)[] Delta)> FieldCache = new();

    public readonly Dictionary<NetEntity, Entry> Entities = new();

    public void Apply(EntityState state)
    {
        if (!Entities.TryGetValue(state.NetEntity, out var entry))
        {
            entry = new Entry();
            Entities[state.NetEntity] = entry;
        }

        entry.LastModified = state.EntityLastModified;

        if (state.NetComponents != null)
        {
            entry.NetComponents = new HashSet<ushort>(state.NetComponents);
            foreach (var netId in entry.Components.Keys.Where(x => !state.NetComponents.Contains(x)).ToList())
                entry.Components.Remove(netId);
            foreach (var netId in entry.PendingDeltas.Keys.Where(x => !state.NetComponents.Contains(x)).ToList())
                entry.PendingDeltas.Remove(netId);
        }

        foreach (var change in state.ComponentChanges.Span)
        {
            entry.NetComponents?.Add(change.NetID);

            if (change.State is not IComponentDeltaState delta)
            {
                entry.Components[change.NetID] = change;
                entry.PendingDeltas.Remove(change.NetID);
                continue;
            }

            if (entry.Components.TryGetValue(change.NetID, out var existing) && existing.State != null)
            {
                entry.Components[change.NetID] = new ComponentChange(change.NetID, delta.CreateNewFullState(existing.State), change.LastModifiedTick);
                continue;
            }

            if (entry.PendingDeltas.TryGetValue(change.NetID, out var pending)
                && pending.State is IAutoGeneratedComponentDeltaState older
                && delta is IAutoGeneratedComponentDeltaState newer
                && older.GetType() == newer.GetType())
            {
                entry.PendingDeltas[change.NetID] = new ComponentChange(change.NetID, MergeDeltas(older, newer), change.LastModifiedTick);
                continue;
            }

            entry.PendingDeltas[change.NetID] = change;
        }
    }

    public void Delete(NetEntity entity)
    {
        Entities.Remove(entity);
    }

    public EntityState? Snapshot(NetEntity entity, HashSet<ushort>? hidden, bool includePending = true)
    {
        if (!Entities.TryGetValue(entity, out var entry))
            return null;

        var changes = new List<ComponentChange>(entry.Components.Count + entry.PendingDeltas.Count);
        foreach (var (netId, change) in entry.Components)
        {
            if (hidden == null || !hidden.Contains(netId))
                changes.Add(change);
        }

        if (includePending)
        {
            foreach (var (netId, change) in entry.PendingDeltas)
            {
                if (hidden == null || !hidden.Contains(netId))
                    changes.Add(change);
            }
        }

        HashSet<ushort>? netComps = null;
        if (entry.NetComponents != null)
        {
            netComps = new HashSet<ushort>(entry.NetComponents);
            if (hidden != null)
                netComps.ExceptWith(hidden);
        }

        return new EntityState(entity, changes, entry.LastModified, netComps);
    }

    public static EntityState Strip(EntityState state, HashSet<ushort> hidden)
    {
        var span = state.ComponentChanges.Span;
        var changes = new List<ComponentChange>(span.Length);
        foreach (var change in span)
        {
            if (!hidden.Contains(change.NetID))
                changes.Add(change);
        }

        HashSet<ushort>? netComps = null;
        if (state.NetComponents != null)
        {
            netComps = new HashSet<ushort>(state.NetComponents);
            netComps.ExceptWith(hidden);
        }

        return new EntityState(state.NetEntity, changes, state.EntityLastModified, netComps);
    }

    private static IComponentState MergeDeltas(IAutoGeneratedComponentDeltaState older, IAutoGeneratedComponentDeltaState newer)
    {
        var type = newer.GetType();
        if (!FieldCache.TryGetValue(type, out var fields))
        {
            var all = type.GetFields(BindingFlags.Instance | BindingFlags.Public | BindingFlags.NonPublic);
            var delta = all
                .Select(f => (Field: f, Attr: f.GetCustomAttribute<NetworkedDeltaFieldAttribute>()))
                .Where(x => x.Attr != null)
                .Select(x => (x.Field, x.Attr!.Index))
                .ToArray();
            fields = (all, delta);
            FieldCache[type] = fields;
        }

        var merged = (IAutoGeneratedComponentDeltaState) RuntimeHelpers.GetUninitializedObject(type);
        foreach (var field in fields.All)
            field.SetValue(merged, field.GetValue(newer));

        foreach (var (field, index) in fields.Delta)
        {
            var bit = 1UL << index;
            if ((older.ChangedFields & bit) != 0 && (newer.ChangedFields & bit) == 0)
                field.SetValue(merged, field.GetValue(older));
        }

        merged.ChangedFields = older.ChangedFields | newer.ChangedFields;
        return merged;
    }
}
