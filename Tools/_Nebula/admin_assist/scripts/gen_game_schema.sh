#!/bin/sh
# DOTNET_EF=/path/to/dotnet-ef scripts/gen_game_schema.sh
set -eu

here=$(cd "$(dirname "$0")" && pwd)
repo=$(cd "$here/../../../.." && pwd)
out="$here/../tests/fixtures/game_schema.sql"
name=aa-schema-gen
port=55433
ef=${DOTNET_EF:-dotnet ef}

docker rm -f "$name" >/dev/null 2>&1 || true
trap 'docker rm -f "$name" >/dev/null 2>&1 || true' EXIT
docker run -d --name "$name" -e POSTGRES_USER=ss14 -e POSTGRES_PASSWORD=gen -e POSTGRES_DB=ss14 \
    -p "127.0.0.1:$port:5432" --tmpfs /var/lib/postgresql/data postgres:16-alpine >/dev/null

i=0
until docker exec "$name" pg_isready -h 127.0.0.1 -U ss14 >/dev/null 2>&1; do
    i=$((i + 1))
    [ "$i" -lt 60 ] || { echo "postgres did not start" >&2; exit 1; }
    sleep 1
done

(cd "$repo/Content.Server.Database" && $ef database update --context PostgresServerDbContext \
    --connection "Host=127.0.0.1;Port=$port;Database=ss14;Username=ss14;Password=gen")

newest=$(docker exec "$name" psql -U ss14 -d ss14 -Atc \
    'SELECT "MigrationId" FROM "__EFMigrationsHistory" ORDER BY 1 DESC LIMIT 1')

{
    echo "-- GENERATED by scripts/gen_game_schema.sh from the game's EF Core migrations. Do not edit."
    echo "-- For local tests only; never run this against a real database."
    echo "-- Schema as of migration: $newest"
    echo
    docker exec "$name" pg_dump -U ss14 -d ss14 --schema-only --no-owner --no-privileges \
        | grep -v -e '^\\restrict ' -e '^\\unrestrict '
} > "$out"

echo "wrote $out (schema as of $newest)"
